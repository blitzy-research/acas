    """The record/host-variable attribute name for a COBOL data name.

    The codebase's own convention throughout ``acas_posting.records``: lower-case and
    hyphens to underscores. ``"WS-IRS-Vat-AC-Def"`` becomes ``"ws_irs_vat_ac_def"``
    and ``"HV-IRS-POST-KEY"`` becomes ``"hv_irs_post_key"``.
    """
