def _fetch_record_into_host_variables(row: Mapping[str, object]) -> HostVariables:
    """``CALL "MySQL_fetch_record" USING WS-MYSQL-RESULT <ten host variables>``
    [common/slpostingMT.cbl:L503-L517].

    The expansion of ``/MYSQL FETCH\\ TABLE=PSIRSPOST-REC``
    [common/slpostingMT.scb:L467-L469] names the ten host variables POSITIONALLY, in
    the order ``HV-IRS-POST-KEY`` through ``HV-IRS-VAT-AMOUNT``
    [common/slpostingMT.cbl:L505-L514] - which is column ordinal order, so the C
    routine fills variable *n* from column *n*. Driven from :data:`COLUMNS` here for
    exactly that reason.

    THE CONVERSION IS ``cob_move`` INTO EACH DECLARED HOST VARIABLE, and it is not the
    inverse of the write path:

    * An alphanumeric ``PIC X(n)`` receives the column's text left-justified and
      SPACE-PADDED to *n*. This matters because MySQL STRIPS trailing spaces when it
      returns a ``CHAR`` column, so ``IRS-POST-CODE`` stored as ``"A "`` comes back as
      ``"A"`` and the host variable has to pad it back to two.
    * A numeric ``COMP`` item receives the text PARSED NUMERICALLY, sign included.
      MEASUREMENT P4-E: ``"-0001234.56"`` read back into
      ``PIC S9(07)V9(02) COMP`` yields ``-1234.56``, sign intact - so THE SIGN PATH IS
      ASYMMETRIC (measurement M-5). The write drops the sign, because
      ``WS-MYSQL-EDIT``'s slice starts past it (measurement M-2, anomaly N-SIGNDROP);
      the read preserves it. A negative amount can therefore be read out of a row that
      this bridge could not have written with one.

    Args:
        row: one record of the stored result, keyed by column name.

    Returns:
        The ten host variables, filled.

    Raises:
        KeyError: if the row is missing a column. ``SELECT *`` over the frozen table
            always returns all ten, so this is a Python caller's error, not a data
            condition - and rule R-3 forbids adding a validation of accounting data,
            which this is not.
    """
    hv = HostVariables.initialize()
    for binding in COLUMNS:
        value = row[binding.column]
        current = getattr(hv, binding.host_variable_attribute)
        if isinstance(current, str):
            # `PIC X(n)` receives text, left-justified and space-padded.
            width = len(current)
            text = "" if value is None else str(value)
            setattr(hv, binding.host_variable_attribute, text[:width].ljust(width))
        elif isinstance(current, Decimal):
            # `PIC S9(07)V9(02) COMP`. The pinned converter in
            # `dal/connection.py` guarantees a `decimal` column arrives as a
            # `Decimal`, never a float (rule R-2), so this is a re-scale and never a
            # binary conversion.
            setattr(
                hv,
                binding.host_variable_attribute,
                Decimal(0) if value is None else Decimal(str(value)),
            )
        else:
            # `PIC 9(n) COMP` and `PIC S9(18) COMP`.
            setattr(
                hv,
                binding.host_variable_attribute,
                0 if value is None else int(value),
            )
    return hv


