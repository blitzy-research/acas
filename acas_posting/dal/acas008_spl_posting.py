def ba040_process_read_next(
    file_access: FileAccess,
    dal_common: AcasDalCommonData,
    irs_posting: WsIrsPostingRecord,
) -> None:
    """``ba040-Process-Read-Next.`` [common/slpostingMT.cbl:L427] and ``ba041-Reread.``
    [:L492].

    THE SEQUENTIAL READ, and the only verb of the five that returns data.

    The paragraph builds a positioning ``SELECT`` whose ``WHERE`` is the one predicate
    ``` `IRS-POST-KEY` >= "0000000000" ``` with ``ORDER BY `IRS-POST-KEY` ASC``
    [common/slpostingMT.cbl:L436-L446], stores the result, and then ``ba041-Reread``
    fetches ONE row per call [:L492-L551]. On the first call it selects and fetches; on
    every later call it fetches only, because ``Most-Cursor-Set`` is already 1
    [:L475].

    DELEGATED IN FULL to :func:`~acas_posting.dal.cursor_state.read_next`, which owns
    the statement, the store-result, the one-row-per-call fetch, the sticky end-of-file
    test and the ``WS-File-Key`` tags ``"00000"`` [:L471], ``"No Data"`` [:L487],
    ``"EOF"`` [:L521], ``"EOF2"`` [:L535] and ``"EOF3"`` [:L543]. That module is the
    single implementation of ISAM cursor emulation for every in-scope table and its
    anomaly set for this path is documented there; re-deriving it here would give the
    run two cursors for one table.

    ``move HV-IRS-POST-KEY to WS-File-Key`` at [:L548] and [:L642] is inside that
    delegated region, and the module's own tag handling covers it.

    THE FETCHED ROW IS UNLOADED BY THIS PARAGRAPH, not by the cursor module: the
    bridge performs ``bb100-UnloadHVs`` at [:L546] and [:L641], so the row lands in the
    caller's record through :func:`bb100_unload_hvs` - including the asymmetric key
    conversion documented there.

    A RAW CURSOR IS REQUIRED, not :func:`~acas_posting.dal.connection.execute_statement`
    - the delegate issues the ``execute`` itself and then stores the result, so it must
    be handed a cursor that has not run anything yet.
    """
    ws = working_storage()
    log = file_access.logging_data
    # `move spaces to WS-Log-Where.` [common/slpostingMT.cbl:L496] and
    # `move 3 to ws-No-Paragraph.` [:L435]. The paragraph number is 3 for the
    # positioning SELECT and 4 for the FETCH [:L497]; the delegate performs both, so
    # the number it ends on is the one the log carries.
    log.ws_no_paragraph = _BRIDGE_PARA_SELECT
    if ws.connection is None:
        # Unreachable through `acas008`, which opens before it reads. Reported as the
        # copybook reports a dead connection rather than raised, for the same reason
        # as in `ba020_process_open`.
        _LOG.error(
            "%s/%s paragraph %d: read-next requested with no open connection",
            HANDLER_NAME,
            BRIDGE_NAME,
            _BRIDGE_PARA_SELECT,
        )
        file_access.fs_reply = int(FsReply.ERROR)
        file_access.we_error = int(WeError.RDB_INIT_ERROR)
        ba999_end(file_access, dal_common)
        return
    # A RAW cursor: the delegate issues the `execute` and stores the result itself.
    # `states=` hands it the BRIDGE's own `01 DAL-Data`, not the shared default - see
    # :attr:`WorkingStorage.cursor_states`. `file_access=` lets it apply its own
    # outcome, which is how `move zero to fs-reply WE-Error` [:L549], the
    # `WS-File-Key` tag [:L548] and `WS-Log-Where` [:L434] all get written; doing any
    # of that a second time here would risk disagreeing with it.
    with contextlib.closing(ws.connection.cursor()) as cursor:
        outcome: CursorOutcome = _cursor_read_next(
            cursor,
            TABLE_NAME,
            slot=CursorSlot.PRIMARY,
            states=ws.cursor_states,
            file_access=file_access,
        )
    # `perform bb100-UnloadHVs.` [common/slpostingMT.cbl:L546] and [:L641] - performed
    # ONLY on the delivering path. Neither the end-of-file branch [:L519-L523] nor the
    # zero-rows branch [:L463-L474] unloads, so on those the caller keeps whatever was
    # in its record before the call, and that is reproduced by not touching it.
    #
    # THE ONE `with filler` SITE IS ITSELF UNREACHABLE. `initialize
    # WS-IRS-Posting-Record with filler` [:L534] sits inside `if WS-MYSQL-Count-Rows =
    # zero` [:L526] AND `if WS-MYSQL-Error-Number not = "0  "` [:L528], within
    # `ba041-Reread` - which is only entered when the cursor is active, and the cursor
    # is only active when the positioning SELECT returned rows, which is exactly when
    # count-rows is NOT zero. So the whole `"EOF2"` branch [:L526-L539] is dead code in
    # the frozen bridge. Recorded under N-INITIALIZE; implemented nowhere, because
    # there is no compiled behaviour to reproduce.
    if outcome.row is not None:
        ws.host_variables = _fetch_record_into_host_variables(outcome.row)
        bb100_unload_hvs(ws.host_variables, irs_posting)
    # `go to ba999-End.` [common/slpostingMT.cbl:L550] - Agent Action Plan section
    # 0.4.2 CLASS 2. Every exit from `ba040`/`ba041` reaches `ba999-End` except the
    # zero-rows branch, which transfers to `ba998-Free` [:L474] and falls through into
    # `ba999-End` from there - the same post-loop work either way.
    ba999_end(file_access, dal_common)


