def aa010_main(
    system: SystemRecord,
    irs_posting: WsIrsPostingRecord,
    file_access: FileAccess,
    file_defs: FileDefs,
    dal_common: AcasDalCommonData,
) -> None:
    """``aa010-main.`` [common/acas008.cbl:L289] - THE WHOLE OF THE HANDLER'S LOGIC.

    Reproduced statement for statement in the COBOL's order. The order is the point:
    the guard runs before the coercion, the coercion before the store decision, and the
    store decision before the record-length check.

    PRECISELY WHAT A REJECTED VERB LEAVES BEHIND - and the brief's summary of this is
    slightly too strong, so it is spelled out from the source rather than repeated.
    ``move 1 to WS-Log-System`` and ``move 15 to WS-Log-File-No``
    [common/acas008.cbl:L293-L294] come BEFORE the ``evaluate`` at [:L299], so a
    rejected verb DOES leave the log identity set, to (1, 15). What it does NOT touch:
    the log-file number is never advanced to the RDB-path value 25 [:L523], no
    connection is opened, no credentials are read, ``SQL-Err``/``SQL-Msg``/``SQL-State``
    are left exactly as the caller passed them, the record is not read or written, and
    no cursor is created. So the observable residue of a rejection is three fields -
    ``WS-Log-System``, ``WS-Log-File-No``, and the ``FS-Reply``/``WE-Error`` pair the
    guard itself sets - and nothing else.

    ::

        L293  move     1      to WS-Log-System.
        L294  move     15     to WS-Log-File-No.
        L299  evaluate File-Function                  <- THE GUARD
        L300           when  4  / when 7 / when 9 / when 8
        L304                    move 988 to WE-Error
        L305                    move 99  to fs-reply
        L306                    go   to aa999-main-exit
        L307  end-evaluate.
        L313  if       fn-Open and fn-output          <- COERCION SITE 1
        L315      and  not FS-Cobol-Files-Used
        L316           set fn-delete-all to true
        L317           perform ba-Process-RDBMS
        L318           go to AA-Main-Exit
        L319  end-if.
        L323  if       not FS-Cobol-Files-Used        <- THE RDB FAN-OUT
        L324           move RDBMS-Flat-Statuses to FA-RDBMS-Flat-Statuses
        L325           perform ba-Process-RDBMS
        L326           go to AA-Main-Exit
        L327  end-if.
        L332  if       fn-Delete-All                  <- THE COBOL BACK-STOP
        L333      and  FS-Cobol-Files-Used
        L334           set fn-open   to true
        L335           set fn-output to true
        L336  end-if.
        L340  perform  ba012-Test-WS-Rec-Size-2.
        L352  move     spaces to SQL-Err SQL-Msg SQL-State.
        L354  evaluate File-Function                  <- THE COBOL DISPATCH
        ...   1 -> aa020, 2 -> aa030, 3 -> aa040, 5 -> aa070, other -> aa100
        L375  end-evaluate.
        L378  go       to aa100-Bad-Function.

    THE GUARD, ANOMALY #6, is [:L299-L307] and it is the reason the Agent Action Plan
    names this module by hand in section 0.7.2 R-4. Four points of fidelity:

    1. THE REJECTED SET IS 4, 7, 9, 8 - read-indexed, re-write, start, delete - and the
       maintainer's own heading says why [:L296-L297]: "Now Test for start,
       read-indexed, rewrite and delete / RDB may be different so need to check."
    2. THE ``when`` ORDER IS 4, 7, 9, 8 AND IT IS NOT NUMERIC. Preserved, from
       :data:`REJECTED_FUNCTIONS`, which is
       ``dal/cursor_state.py``'s transcription and is ordered the same way.
    3. THE STATUS PAIR IS ``WE-Error 988`` [:L304] then ``FS-Reply 99`` [:L305], in
       that order. ``988`` appears NOWHERE in the authoritative status table at
       [common/glpostingMT.cbl:L125-L158]; it is this handler's private code with its
       own wording, "Action type wrong for file type (seq)" [:L304].
    4. IT IS AT ENTRY - before the Cobol/RDB decision, before the record-length guard,
       before any credential load - SO NO STATE OF ANY KIND IS TOUCHED. A rejected verb
       does not open a connection, does not change the log-file number, does not clear
       ``SQL-Err``, and issues no SQL.

    IT RETURNS THE PAIR; IT DOES NOT RAISE. Agent Action Plan section 0.6.5 is explicit:
    "The Python module reproduces the guard, returning the same status pair rather than
    performing an update."

    THE COERCION, [:L313-L319], is the other half of what this module is named for. It
    is COERCION AND NOT SEQUENCING: ``set fn-delete-all to true`` [:L316] runs BEFORE
    ``perform ba-Process-RDBMS`` [:L317], so the bridge is entered ONCE with the
    function already replaced. Contrast the siblings and preserve all three -
    ``acas005`` has the block COMMENTED OUT [common/acas005.cbl:L309-L314] because "NOT
    used with GL." [:L307], and ``acas006``/``acas007`` perform the bridge with NO
    ``set`` and then set it in ``ba015-Test-Ends`` and fall through into a second
    bridge call [common/acas006.cbl:L640-L653].

    THE FAN-OUT, [:L323-L327], is the RDB path for every other verb.
    ``move RDBMS-Flat-Statuses to FA-RDBMS-Flat-Statuses`` [:L324] copies the store
    selector from the SYSTEM record into ``File-Access`` for the bridge's benefit, with
    the maintainer's note "needed for DAL? not JC/dbpre versions" - and the JC bridge
    this module reproduces indeed never reads it. Copied anyway, because it is a write
    to a linkage item the caller can see.

    THE BACK-STOP, [:L332-L336], is the coercion's mirror image: on the COBOL path a
    delete-all becomes an ``open output``, which is how the flat file gets emptied. It
    is recorded and reproduced even though the Cobol leg has no store, because it
    explains why the coercion is written twice - the two paths need the request in
    opposite forms.

    ``move zero to WE-Error FS-Reply`` is COMMENTED OUT at [:L350-L351], with the
    maintainer's own ``?`` on both lines - the same reluctance the bridge shows at
    [common/slpostingMT.cbl:L327-L328]. So the Cobol dispatch runs with the caller's
    incoming status intact. Only ``SQL-Err``, ``SQL-Msg`` and ``SQL-State`` are cleared
    [:L352], and note that this is a THIRD clearing convention: spaces into all three,
    where ``ba010-Initialise`` clears ``SQL-Err`` to spaces [:L335] and ``ba070`` to
    zero [:L752].

    THE COBOL DISPATCH [:L354-L375] lists only 1, 2, 3 and 5. ``when 4``, ``when 7``,
    ``when 8`` and ``when 9`` are all COMMENTED OUT [:L362-L372] - a second, independent
    refusal of the same four verbs, and the reason
    :func:`aa080_process_delete` is dead twice over. The ``when other`` comment reads "6
    is unused" [:L373], which is wrong the same way the bridge's is: 6 is DELETE-ALL, the
    function this handler itself coerces into.

    ``go to aa100-Bad-Function`` at [:L378] is unreachable after an ``evaluate`` whose
    ``when other`` already transfers, and the maintainer says so: "Should never get here
    but in case :(" [:L377]. Reproduced as the unreachable back-stop it is.
    """
    log = file_access.logging_data
    # ---- For logging only [common/acas008.cbl:L291] ----
    # `move 1 to WS-Log-System.` [common/acas008.cbl:L293]. N-LOGSYSTEM: the value is
    # 1 = IRS even though this handler serves SALES and PURCHASE - the maintainer's own
    # enumeration is on the line, "1 = IRS, 2=GL, 3=SL, 4=PL, 5=Stock". Preserved as
    # written; `LogSystem.IRS` is the imported name for it.
    log.ws_log_system = int(WS_LOG_SYSTEM)
    # `move 15 to WS-Log-File-No.` [common/acas008.cbl:L294] - overwritten to 25 by
    # `ba010-Test-WS-Rec-Size` on the RDB path (N-LOGFILE).
    log.ws_log_file_no = WS_LOG_FILE_NO_COBOL
    # ---- THE GUARD [common/acas008.cbl:L299-L307] - FIRST, before anything else ----
    # `REJECTED_FUNCTIONS` is keyed by `FileFunction`, an `IntEnum`, so a plain
    # `File-Function` value keys it directly - which is what the COBOL `evaluate` does
    # with the numeric literals 4, 7, 9 and 8.
    rejected = REJECTED_FUNCTIONS.get(file_access.file_function)
    if rejected is not None:
        fs_reply, we_error, locator = rejected
        # `move 988 to WE-Error` [common/acas008.cbl:L304] then
        # `move 99 to fs-reply` [:L305], in that order.
        file_access.we_error = int(we_error)
        file_access.fs_reply = int(fs_reply)
        _LOG.debug(
            "%s refused File-Function %d: %s",
            HANDLER_NAME,
            file_access.file_function,
            locator,
        )
        # `go to aa999-main-exit` [common/acas008.cbl:L306] - Agent Action Plan
        # section 0.4.2 CLASS 3.
        aa999_main_exit(file_access, dal_common)
        return
    # ---- COERCION SITE 1 [common/acas008.cbl:L313-L319] ----
    if (
        file_access.file_function == FileFunction.OPEN
        and file_access.access_type == AccessType.OUTPUT
        and not _fs_cobol_files_used(system)
    ):
        # `set fn-delete-all to true` [common/acas008.cbl:L316] - BEFORE the perform,
        # so the bridge sees 6 and is entered exactly ONCE.
        file_access.file_function = int(COERCED_FUNCTION)
        # `perform ba-Process-RDBMS` [common/acas008.cbl:L317]
        ba_process_rdbms(system, file_access, dal_common, irs_posting)
        # `go to AA-Main-Exit` [common/acas008.cbl:L318] - Class 3, and note it lands
        # at `aa-main-exit` and NOT at `aa999-main-exit`, so the handler's own log is
        # skipped.
        aa_main_exit()
        return
    # ---- THE RDB FAN-OUT [common/acas008.cbl:L323-L327] ----
    if not _fs_cobol_files_used(system):
        # `move RDBMS-Flat-Statuses to FA-RDBMS-Flat-Statuses`
        # [common/acas008.cbl:L324]
        file_access.fa_rdbms_flat_statuses.fa_file_system_used = (
            system.system_data_block.rdbms_flat_statuses.file_system_used
        )
        # `perform ba-Process-RDBMS` [common/acas008.cbl:L325] - the maintainer's
        # comment is "Can't hurt".
        ba_process_rdbms(system, file_access, dal_common, irs_posting)
        # `go to AA-Main-Exit` [common/acas008.cbl:L326] - Class 3.
        aa_main_exit()
        return
    # ---- THE COBOL BACK-STOP [common/acas008.cbl:L332-L336] ----
    if (
        file_access.file_function == FileFunction.DELETE_ALL
        and _fs_cobol_files_used(system)
    ):
        # `set fn-open to true` [common/acas008.cbl:L334] and `set fn-output to true`
        # [:L335] - a delete-all becomes an open-output, the mirror of coercion site 1.
        file_access.file_function = int(FileFunction.OPEN)
        file_access.access_type = int(AccessType.OUTPUT)
    # `perform ba012-Test-WS-Rec-Size-2.` [common/acas008.cbl:L340] - the PARAGRAPH,
    # not the section, so `ba010-Test-WS-Rec-Size` is skipped and the log-file number
    # stays 15 on this path (N-LOGFILE).
    ba012_test_ws_rec_size_2(system, file_access, dal_common)
    # `move zero to WE-Error FS-Reply` is COMMENTED OUT at [common/acas008.cbl:L350-L351]
    # and is deliberately not reproduced.
    # `move spaces to SQL-Err SQL-Msg SQL-State.` [common/acas008.cbl:L352] - the third
    # clearing convention; this one includes `SQL-State`, which neither of the bridge's
    # two clearings touches.
    _clear_sql_fields(log)
    log.sql_state = " " * SQL_STATE_WIDTH
