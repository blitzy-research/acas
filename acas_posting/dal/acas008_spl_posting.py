def _record_driver_failure(
    error: BaseException, statement: str, *, paragraph: int
) -> None:
    """Log one driver failure without leaking or forging anything.

    The bridge's response to a failed statement is to call ``MySQL_error`` and store
    the server's text [common/slpostingMT.cbl:L758-L760]. That text is built from
    material that can include the account, the host and key values from the data, and
    it can carry a carriage return - so it is redacted and its control characters
    escaped before it reaches a log (CWE-532, CWE-117). Nothing branches on the
    result: the status pair each caller reports is the one the frozen source dictates,
    chosen by the exception being caught at all and never by what it said.
    """
    _LOG.warning(
        "%s/%s paragraph %d: %s (%s) on %s",
        HANDLER_NAME,
        BRIDGE_NAME,
        paragraph,
        type(error).__name__,
        db_error_log_category(str(getattr(error, "errno", "") or "")),
        sanitise_for_log(redact_for_log(statement)),
    )


def _driver_error_fields(error: BaseException) -> tuple[str, str, str]:
    """The three values ``Mysql-1100-Db-Error`` reads out of a failed statement.

    ``call "MySQL_errno"`` [copybooks/mysql-procedures.cpy:L97], ``call "MySQL_error"``
    [:L107] and ``call "MySQL_sqlstate"`` [:L122]. Read by ``getattr`` rather than by
    catching a driver-specific class, which is the same choice
    ``dal/cursor_state.py`` makes: this module must not acquire a hard dependency on
    the connector's exception hierarchy in order to read three attributes off it.

    Returns:
        ``(errno as text, message, SQLSTATE)``. Each is the empty string when the
        exception does not carry it, which is what a non-server failure looks like.
    """
    errno = getattr(error, "errno", None)
    message = getattr(error, "msg", None)
    sql_state = getattr(error, "sqlstate", None)
    return (
        str(errno) if isinstance(errno, int) and errno > 0 else "",
        str(message) if message else str(error),
        str(sql_state) if sql_state else "",
    )


