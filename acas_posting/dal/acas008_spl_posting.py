#: dictionary entries are keyed under the RECORD rather than the table, which is the
#: dictionary's own way of recording a field with no column, and they are cited here
#: so the omission is evidenced rather than asserted. ``copybooks/wspost-irs.cob``
#: declares no ``FILLER``, so these two are the only such fields.
KEY_SUBFIELDS_WITHOUT_COLUMNS: Final[tuple[str, ...]] = tuple(
    loader.cite(descriptor.dictionary_key)
    for descriptor in WsIrsPostKey.FIELDS
    if descriptor.dictionary_key is not None
)


def render_column(binding: ColumnBinding, value: Decimal | int | str) -> str:
    """Render one host-variable value exactly as ``bb200-Insert`` renders it.

    Reproduces the per-column blocks of [common/slpostingMT.cbl:L1051-L1176]. Each
    block emits ``'`COL`="'``, then the rendered text, then ``'"'`` - so EVERY VALUE
    REACHES MySQL AS A QUOTED STRING, including the numeric columns, and the server
    coerces it. That is reproduced by binding the rendered TEXT as a parameter, which
    keeps the coercion on the server side where the COBOL leaves it.

    Two anomalies are applied here, both from measurement M-2: the key loses its most
    significant digit and every numeric value loses its sign, because no slice the
    bridge takes ever reads position 1 of ``WS-MYSQL-EDIT``.

    Args:
        binding: The column, carrying its renderer and that renderer's locator.
        value: The host variable's value.

    Returns:
        The text the bridge would have placed between the two double quotes.

    Raises:
        TypeError: If the value's Python type cannot be the host variable's.
    """
    renderer = binding.renderer
    if renderer is Renderer.TRIM_TRAILING:
        if not isinstance(value, str):
            raise TypeError(
                f"{binding.host_variable} is a character host variable "
                f"{binding.load_source}; got {type(value).__name__}"
            )
        # `FUNCTION TRIM (hv,TRAILING)` - measurement M-3 makes an all-space field
        # the EMPTY STRING here, not a run of spaces.
        return function_trim_trailing(value)

    if isinstance(value, str):
        raise TypeError(
            f"{binding.host_variable} is a numeric host variable "
            f"{binding.load_source}; got str"
        )
    edit = ws_mysql_edit(value)
    if renderer is Renderer.EDIT_03_18:
        # `FUNCTION TRIM (WS-MYSQL-EDIT(03:18))` - starts at position 3, so both the
        # sign AND the first integer digit are skipped [common/slpostingMT.cbl:L1062].
        return function_trim(edit_slice(edit, 3, 18))
    if renderer is Renderer.EDIT_11_10:
        return function_trim(edit_slice(edit, 11, 10))
    if renderer is Renderer.EDIT_18_03:
        return function_trim(edit_slice(edit, 18, 3))
    # `Renderer.EDIT_14_07_DOT_22_02`: the decimal point is assembled by hand from
    # three separate `string` statements [common/slpostingMT.cbl:L1163-L1170], and
    # position 1 - the sign - is never among them.
    return f"{function_trim(edit_slice(edit, 14, 7))}.{edit_slice(edit, 22, 2)}"



