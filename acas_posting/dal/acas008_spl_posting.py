def _insert_statement(hv: HostVariables) -> tuple[str, tuple[str, ...]]:
    """Build the ``INSERT`` the translator generated, as text plus bound values.

    ``bb200-Insert Section.`` expands ``/MYSQL INSERT\\ TABLE=PSIRSPOST-REC``
    [common/slpostingMT.scb:L937-L939] into a hand-rolled command builder
    [common/slpostingMT.cbl:L1051-L1177]::

        INITIALIZE WS-MYSQL-COMMAND
        MOVE 1 TO WS-MYSQL-I
        STRING 'INSERT INTO ' '`PSIRSPOST-REC` SET '
               INTO WS-MYSQL-COMMAND WITH POINTER WS-MYSQL-I
        ... per column:  '`COL`="'  <rendered value>  '"'  ', '
        ... then:        '"'  ";"  X"00"
        PERFORM MYSQL-1210-COMMAND THRU MYSQL-1219-EXIT

    So the shape is MySQL's ``INSERT ... SET`` extension, all ten columns are named,
    the values are rendered to TEXT and quoted, and the whole thing ends in a
    semicolon.

    WHY THE VALUES ARE BOUND RATHER THAN INTERPOLATED. The COBOL splices the rendered
    text into the command; this builds the identical text and hands it to the driver
    as a parameter. The value the server receives is the same either way - a quoted
    string literal it coerces to the column's type - so behaviour is unchanged, while
    an interpolated build would be an injection defect (CWE-89) that no rule here
    asks for. The identifiers, which cannot be parameters, go through
    :func:`~acas_posting.dal.connection.quote_identifier`; every one of them contains
    a hyphen and is a syntax error unquoted.

    ``Ws-Mysql-Command (1:6)`` is the only part of the command text anything reads -
    ``Mysql-1100-Db-Error`` tests it for ``"INSERT"``
    [copybooks/mysql-procedures.cpy:L100-L102] - and it is ``"INSERT"`` in both forms.

    THE RENDERING IS WHERE VALUES CHANGE, not here: :func:`render_column` applies each
    column's ``WS-MYSQL-EDIT`` slice, which is what drops the sign from the two money
    fields and the leading digit from the key.

    Args:
        hv: the loaded host-variable group.

    Returns:
        ``(statement, parameters)`` with one ``%s`` placeholder per column, in column
        ordinal order.
    """
    assignments: list[str] = []
    parameters: list[str] = []
    for binding in COLUMNS:
        # `STRING '`' 'COL' '`="' ...` - the identifier is quoted, the value bound.
        assignments.append(f"{quote_identifier(binding.column)}=%s")
        parameters.append(
            render_column(binding, getattr(hv, binding.host_variable_attribute))
        )
    # `'INSERT INTO ' '`PSIRSPOST-REC` SET '` [common/slpostingMT.cbl:L1053-L1056],
    # then `', '` between columns [:L1068 and every following block], then `";"`
    # [:L1173].
    statement = (
        f"INSERT INTO {quote_identifier(TABLE_NAME)} SET "
        + ", ".join(assignments)
        + ";"
    )
    return (statement, tuple(parameters))


def bb200_insert(
    connection: Any,
    hv: HostVariables,
    file_access: FileAccess,
    dal_common: AcasDalCommonData,
) -> None:
    """``bb200-Insert Section.`` [common/slpostingMT.cbl:L1043].

    Builds the command (:func:`_insert_statement`) and performs
    ``MYSQL-1210-COMMAND THRU MYSQL-1219-EXIT`` [common/slpostingMT.cbl:L1177], which
    is [copybooks/mysql-procedures.cpy:L164-L181]::

        call "MySQL_query" using WS-Mysql-Command.
        if Return-Code not = zero
           perform Mysql-1100-Db-Error Thru Mysql-1190-Exit
        end-if
        call "MySQL_affected_rows" using WS-Mysql-Count-Rows.

    THE AFFECTED-ROWS CALL IS UNCONDITIONAL [:L178] - it runs whether or not the query
    failed - so ``WS-MYSQL-COUNT-ROWS`` is always refreshed, and it is zero after a
    failure. That is what makes ``ba070``'s ``if WS-MYSQL-COUNT-ROWS not = 1`` test
    [common/slpostingMT.cbl:L755] fire on both a failed insert and a curiously
    successful one.

    THE ERROR HANDLING IS THE COPYBOOK'S, NOT THIS MODULE'S.
    :func:`~acas_posting.dal.status.mysql_1100_db_error` owns
    ``Mysql-1100-Db-Error`` including its duplicate-key shortcut, which is where
    N-DUPKEY lives: a duplicate insert leaves ``We-Error`` at zero and ``SQL-State``
    at spaces because the branch transfers out before either is set
    [copybooks/mysql-procedures.cpy:L99-L105]. Re-deriving that here would give the
    run two disagreeing notions of the same status.

    ``Mysql-1110-Report-Problem`` [copybooks/mysql-procedures.cpy:L130-L137] displays
    the error and ACCEPTS a keystroke. Per Agent Action Plan section 0.3.4 a pause
    whose only effect is to block a terminal is dropped and the display becomes a log
    record; :func:`_record_driver_failure` is that record. The duplicate-key path
    never reaches the display anyway, having transferred out at [:L104].

    Args:
        connection: the live connection standing in for ``Ws-Mysql-Cid``.
        hv: the loaded host-variable group.
        file_access: the caller's block. ``WS-Count-Rows`` and, on failure, the four
            status fields are written into it.
        dal_common: the testing switches.
    """
    log = file_access.logging_data
    statement, parameters = _insert_statement(hv)
    try:
        # `call "MySQL_query" using WS-Mysql-Command.`
        # [copybooks/mysql-procedures.cpy:L165]
        with execute_statement(connection, statement, parameters) as cursor:
            affected = cursor.rowcount
    except Exception as error:  # any driver error takes this path - see below
        # `if Return-Code not = zero / perform Mysql-1100-Db-Error Thru
        #  Mysql-1190-Exit` [copybooks/mysql-procedures.cpy:L166-L177]. The bridge
        # branches on the query's return code alone and never on which error it was,
        # so catching `Exception` is the faithful width.
        _record_driver_failure(error, statement, paragraph=_BRIDGE_PARA_INSERT)
        errno, message, sql_state = _driver_error_fields(error)
        status = mysql_1100_db_error(
            errno=errno,
            message=message,
            sql_state=sql_state,
            command=statement,
            we_error=file_access.we_error,
        )
        file_access.fs_reply = int(status.fs_reply)
        file_access.we_error = int(status.we_error)
        log.sql_err = status.sql_err
        log.sql_msg = status.sql_msg
        log.sql_state = status.sql_state
        # `call "MySQL_affected_rows" using WS-Mysql-Count-Rows.` [:L178] - reached on
        # the failure path too, because it sits AFTER the `end-if`.
        log.ws_count_rows = 0
        if _testing_1(dal_common):
            ca_process_logs(file_access, dal_common)
        return
    # `call "MySQL_affected_rows" using WS-Mysql-Count-Rows.`
    # [copybooks/mysql-procedures.cpy:L178]
    log.ws_count_rows = affected if affected > 0 else 0


