def _function_length_of_record() -> int:
    """`function Length (WS-Analysis-Record)` and `function length (Analysis-Record)`.

    Computed from the record descriptors rather than written as a literal, so
    that the number is dictionary-derived like every other field fact in this
    module (Agent Action Plan 0.8.1, "data dictionary first"). Walking
    `copybooks/wsanal.cob:L9-L17` gives 1 + 1 + 1 + 6 + 24 + 3 = 36.

    *** ANOMALY N-nofiller-record - RECORDED (rule R-4) ***

    The test is written `A < B` rather than `A not = B`, and the reply move
    beside it explains why: "allow for last field ( FILLER) not being present in
    layout" [common/acas015.cbl:L613]. THIS RECORD HAS NO `filler` AT ANY LEVEL
    [copybooks/wsanal.cob:L9-L17], so the allowance has nothing to allow for -
    and the same absence is why the bridge's two `initialize` forms have
    identical effect here (anomaly N-initialize).

    THE TWO RECORDS ARE THE SAME LENGTH, so one function serves both operands of
    the frozen comparison. `copybooks/fdanal.cob:L9-L17` declares the FD record
    field for field identically to the working-storage record, differing only in
    dropping the `WS-` prefix from the group names; `copybooks/wsanal.cob:L7`
    records why - "24/07/16 vbc - Taken from fdanal.cob". Both headers declare
    "36 bytes" [copybooks/wsanal.cob:L6, copybooks/fdanal.cob:L6], and the field
    sum agrees with both. `A < B` is therefore FALSE on every run and the 901 arm
    is unreachable - which is worth stating, because `copybooks/wsbatch.cob` does
    NOT agree with itself (Agent Action Plan anomaly 15) and would take that arm.

    Returns:
        The record length in bytes.
    """

    total = 0
    # The record's three declaration levels, flattened. `WS-Pa-Code`
    # [copybooks/wsanal.cob:L10] and `Pa-Group` [copybooks/wsanal.cob:L12] are
    # groups and contribute nothing of their own; their members are reached
    # through the two nested classes and are counted exactly once each.
    for descriptor in (
        *WsAnalysisRecord.FIELDS,
        *WsPaCode.FIELDS,
        *PaGroup.FIELDS,
    ):
        if descriptor.is_group:
            continue
        if descriptor.character_length is not None:
            total += int(descriptor.character_length)
        elif descriptor.digits is not None:
            # A DISPLAY numeric occupies one byte per digit; `Pa-Gl` is unsigned
            # [copybooks/wsanal.cob:L15] so there is no sign byte to add.
            total += int(descriptor.digits)
    return total


