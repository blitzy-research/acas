@contextmanager
def _bridge_cursor(connection: object) -> Iterator[object]:
    """Yield a cursor for `dal/cursor_state.py` to execute its own statement on.

    The positioning verbs take a cursor and issue their statement themselves, so they
    cannot go through `execute_statement`, which owns one statement of its caller's.
    This is the narrowest possible bridge between the two.

    Args:
        connection: The connection `mysql_1000_open` returned.

    Yields:
        A DB-API cursor over that connection, or - when another bridge has closed the
            one process handle, anomaly A-8 - the stand-in that reports the driver's
            failure from ``execute``.
    """
    cursor = acquire_cursor(connection)  # type: ignore[arg-type]
    try:
        yield cursor
    finally:
        try:
            cursor.close()
        except Exception:  # noqa: BLE001, S110 - driver-specific, see below
            # A cursor that will not close is not a condition the frozen source
            # has an error path for, and raising from a `finally` would replace
            # the caller's own status with a misleading exception. Dropped,
            # exactly as `connection.py` does for the same case.
            #  NOTHING IS LOGGED AND NO NAME IS BOUND. The frozen bridge has
            #  no cursor-close step at all - `MySQL_query` owns the statement and
            #  the handle - so a record here was invented (R-4), and the record it
            #  replaced interpolated the driver's own text, which for this table
            #  renders the statement and its bound analysis code (CWE-532).
            #  Binding no name means nothing can leak from this block by accident.
            pass


def _affected_rows(cursor: object) -> int:
    """`call "MySQL_affected_rows" using WS-Mysql-Count-Rows`.

    MySQL reports rows CHANGED rather than rows matched, so an UPDATE that assigns a row
    its existing values reports zero. That is not corrected here.

    Args:
        cursor: The cursor the statement was executed on.

    Returns:
        The affected-row count, or zero when the driver does not report one.
    """
    reported = getattr(cursor, "rowcount", None)
    if not isinstance(reported, int) or reported < 0:
        return 0
    return reported


