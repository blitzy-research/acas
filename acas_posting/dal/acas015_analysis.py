def _apply_db_error(logging_data: LoggingData, status: object) -> None:
    """Move the three SQL diagnostic fields from a `Mysql-1100-Db-Error` result.

    The frozen sequence is always the same three foreign calls and three moves
    [common/analMT.cbl:L782-L788, :L837-L843, :L883-L889]::

        call  "MySQL_errno" using WS-MYSQL-Error-Number
        call  "MySQL_sqlstate" using WS-MYSQL-SQLstate
        move  WS-MYSQL-SqlState   to SQL-State
        *> then, inside `if WS-MYSQL-Error-Number (1:1) not = "0"` -
        call "MySQL_error" using Ws-Mysql-Error-Message
        move WS-MYSQL-Error-Number  to SQL-Err
        move WS-MYSQL-Error-Message to SQL-Msg

    `dal/status.py` owns the classification those calls feed, including the
    INSERT special case at [copybooks/mysql-procedures.cpy:L100-L104], so the
    fields are taken from its result rather than recomputed.

    THE THREE INTERMEDIATES ARE REAL AND ARE CROSSED. Each diagnostic lands in
    the bridge's own working storage first and is moved on from there, and one of
    those fields is NARROWER than its destination - anomaly N-msg160, see
    :data:`_WS_MYSQL_ERROR_MESSAGE_WIDTH`. The values are therefore stored into
    the working-storage fields at their declared widths and moved from there,
    which is what truncates a long message at 160 characters exactly as the
    frozen MOVE does.

    Args:
        logging_data: The `Logging-Data` group.
        status: A `DbErrorStatus` from
            :func:`~acas_posting.dal.status.mysql_1100_db_error`.
    """
    # `call "MySQL_errno" ...` / `call "MySQL_sqlstate" ...` /
    # `call "MySQL_error" ...` land in working storage at its declared widths.
    _BRIDGE_WS.ws_mysql_error_number = _move_alphanumeric(
        status.sql_err, _WS_MYSQL_ERROR_NUMBER_WIDTH
    )
    _BRIDGE_WS.ws_mysql_sqlstate = _move_alphanumeric(
        status.sql_state, _WS_MYSQL_SQLSTATE_WIDTH
    )
    _BRIDGE_WS.ws_mysql_error_message = _move_alphanumeric(
        status.sql_msg, _WS_MYSQL_ERROR_MESSAGE_WIDTH
    )
    # ... and are then moved into `File-Access`, the message through the
    # 160-character bottleneck it has just crossed.
    logging_data.sql_err = _LOGGING_FIELDS["SQL-Err"].store(
        _BRIDGE_WS.ws_mysql_error_number
    )
    logging_data.sql_msg = _LOGGING_FIELDS["SQL-Msg"].store(
        _BRIDGE_WS.ws_mysql_error_message
    )
    logging_data.sql_state = _LOGGING_FIELDS["SQL-State"].store(
        _BRIDGE_WS.ws_mysql_sqlstate
    )


