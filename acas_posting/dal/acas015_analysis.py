# =============================================================================
#  COBOL MOVE PRIMITIVES  -  local by necessity, and narrow by design
# =============================================================================
#
# `acas_posting/cobol/*` is NOT importable from this layer: the data-access
# layer may reach `dal.connection`, `dal.status`, `dal.cursor_state`, its own
# record modules and `dictionary.loader`, and nothing else. Where a MOVE is
# between elementary items the record classes already carry the answer - their
# `FIELDS` descriptors perform the store with the receiving field's own
# truncate-and-pad semantics - so those are used directly. Only the three forms
# no descriptor covers are implemented here, each in a handful of lines, each
# with the frozen statement it reproduces:
#
#   * a figurative-constant MOVE into an alphanumeric item, which fills rather
#     than left-justifies - `move zero to SQL-Err` [common/analMT.cbl:L778];
#   * `FUNCTION TRIM`, in both its forms, which the bridge applies to every
#     value it embeds [common/analMT.cbl:L991, :L1002, :L1012, :L1021];
#   * the edited-picture intermediate `WS-MYSQL-EDIT` and the fixed window the
#     bridge slices out of it [common/analMT.cbl:L219, :L1002].
#
# No arithmetic happens in any of them. `PA-GL` is the only numeric column and
# it is an integer end to end - `mediumint(6) unsigned` [mysql/ACASDB.sql:L33] -
# so there is no money in this table and nothing here needs a decimal context.

#: `WS-MYSQL-EDIT PIC -Z(18)9.9(9)` [common/analMT.cbl:L219]. One sign
#: position, eighteen zero-suppressed digit positions, one mandatory digit
#: position, the decimal point, nine decimal positions - thirty characters.
_EDIT_SIGN_POSITIONS: Final[int] = 1
_EDIT_SUPPRESSED_POSITIONS: Final[int] = 18
_EDIT_MANDATORY_POSITIONS: Final[int] = 1
_EDIT_DECIMAL_POSITIONS: Final[int] = 9
_EDIT_INTEGER_POSITIONS: Final[int] = (
    _EDIT_SUPPRESSED_POSITIONS + _EDIT_MANDATORY_POSITIONS
)
_EDIT_TOTAL_POSITIONS: Final[int] = (
    _EDIT_SIGN_POSITIONS
    + _EDIT_INTEGER_POSITIONS
    + 1
    + _EDIT_DECIMAL_POSITIONS
)

#: The reference modification the bridge applies to it: `WS-MYSQL-EDIT(13:08)`
#: [common/analMT.cbl:L1002, :L1064]. One-based position 13, length 8.
_EDIT_WINDOW_START: Final[int] = 13
_EDIT_WINDOW_LENGTH: Final[int] = 8


def _move_alphanumeric(value: str, length: int) -> str:
    """MOVE an alphanumeric item into an alphanumeric item of `length`.

    Left-justified, space-filled on the right, truncated on the right - the
    only rule COBOL has for this case, and the one the record descriptors apply
    for the fields they cover. Used here for the four host variables, whose
    widths come from the dictionary rather than from a picture clause read by
    eye [common/analMT.cbl:L283-L286].

    Args:
        value: The sending item.
        length: The receiving item's character length.

    Returns:
        Exactly `length` characters.
    """
    return value[:length].ljust(length)


def _move_figurative_zero(length: int) -> str:
    """MOVE ZERO into an alphanumeric item of `length`.

    Reproduces `move zero to SQL-Err` [common/analMT.cbl:L778] and
    `move zero to FS-Reply WE-Error SQL-State` [common/analMT.cbl:L776], both of
    which send the figurative constant ZERO into a `pic x(5)` item
    [copybooks/wsfnctn.cob:L49, :L51]. A figurative constant is REPEATED to fill
    the receiving item, so the result is five zero characters and NOT a single
    zero padded with spaces. Getting this backwards would put a different
    five-character string into the log record and into `SQL-Err`, which callers
    test as text [common/analMT.cbl:L789].

    Args:
        length: The receiving item's character length.

    Returns:
        `length` copies of the digit zero.
    """
    return "0" * length


def _function_trim_trailing(value: str) -> str:
    """`FUNCTION TRIM (x, TRAILING)` - remove trailing spaces only.

    The form the bridge applies to all three character host variables before
    embedding them [common/analMT.cbl:L991, :L1012, :L1021, :L1053, :L1074,
    :L1083]. Leading spaces are KEPT, because TRAILING was written; only the
    space character is removed, because that is what TRIM removes.

    Args:
        value: The sending item's current contents.

    Returns:
        The value with trailing spaces removed.
    """
    return value.rstrip(" ")


def _function_trim(value: str) -> str:
    """`FUNCTION TRIM (x)` - remove leading and trailing spaces.

    The unqualified form, which the bridge applies to the edited numeric window
    [common/analMT.cbl:L1002, :L1064] and to the assembled predicate
    [common/analMT.cbl:L1090]. Both need it: the window is right-aligned inside
    a zero-suppressed field, so its spaces are LEADING.

    Args:
        value: The sending item's current contents.

    Returns:
        The value with leading and trailing spaces removed.
    """
    return value.strip(" ")


def _ws_mysql_edit(value: int) -> str:
    """MOVE an integer into `WS-MYSQL-EDIT PIC -Z(18)9.9(9)`.

    Reproduces `MOVE HV-PA-GL TO WS-MYSQL-EDIT` [common/analMT.cbl:L1000-L1001,
    :L1062-L1063] against the declaration at [common/analMT.cbl:L219]. Three
    editing rules apply and all three are observable in the statement text the
    bridge builds:

    * the leading `-` is a fixed insertion character, so it holds a space for a
      non-negative value and the minus sign for a negative one;
    * each `Z` suppresses a LEADING zero, replacing it with a space, and
      suppression stops at the first significant digit - so an interior zero
      still prints;
    * the single `9` before the decimal point is mandatory, so a value of zero
      renders as eighteen spaces followed by one zero digit rather than as an
      entirely blank field.

    The sending field is `HV-PA-GL PIC 9(08) COMP` [common/analMT.cbl:L284], an
    unsigned integer, so the nine decimal positions are always zeros and the
    sign position is always a space. The negative arm is implemented anyway,
    because the picture clause has one and because omitting it would be a
    silent narrowing of the reproduced field rather than a reproduction of it.

    Args:
        value: The integer currently in the host variable.

    Returns:
        Exactly thirty characters, the full edited field.
    """
    magnitude = abs(int(value))
    # High-order digits beyond the nineteen integer positions are lost on the
    # store, exactly as any COBOL MOVE into a narrower numeric field loses them.
    digits = f"{magnitude:0{_EDIT_INTEGER_POSITIONS}d}"[-_EDIT_INTEGER_POSITIONS:]
    suppressible = digits[:_EDIT_SUPPRESSED_POSITIONS]
    mandatory = digits[_EDIT_SUPPRESSED_POSITIONS:]
    significant = suppressible.lstrip("0")
    suppressed = significant.rjust(_EDIT_SUPPRESSED_POSITIONS)
    sign = "-" if int(value) < 0 else " "
    edited = (
        sign
        + suppressed
        + mandatory
        + "."
        + "0" * _EDIT_DECIMAL_POSITIONS
    )
    # The width is a declared property of the field, so it is asserted rather
    # than assumed: a drift here would move the (13:08) window silently.
    if len(edited) != _EDIT_TOTAL_POSITIONS:
        raise AssertionError(
            f"WS-MYSQL-EDIT [common/analMT.cbl:L219] is "
            f"{_EDIT_TOTAL_POSITIONS} characters wide; rendered "
            f"{len(edited)}"
        )
    return edited


def _ws_mysql_edit_window(value: int) -> str:
    """Slice `WS-MYSQL-EDIT(13:08)` - the fixed eight-character window.

    *** ANOMALY N-editwindow - REPRODUCED, NOT FIXED (rule R-4) ***

    [common/analMT.cbl:L1002] and [common/analMT.cbl:L1064] embed the numeric
    column through a FIXED window into the edited field::

        STRING FUNCTION TRIM (WS-MYSQL-EDIT(13:08))

    One-based position 13 through position 20 inclusive. Position 20 is the
    mandatory units digit and position 21 is the decimal point, so the window
    ends exactly at the units digit and excludes the point and all nine decimal
    positions - which is why an integer column survives an edited field that
    carries a fraction. It also spans exactly eight integer digit positions,
    which is exactly the width of `HV-PA-GL PIC 9(08) COMP`
    [common/analMT.cbl:L284], so for every value the host variable can hold the
    window fits.

    IT DOES NOT FIT FOR A WIDER VALUE, AND THE WINDOW IS NOT WIDENED HERE. A
    ninth integer digit renders at position 12, one position to the LEFT of the
    window, and is silently clipped - no error, no diagnostic, a smaller number
    stored. That cannot arise through `bb000_hv_load`, whose store into the host
    variable truncates to eight digits first, but it is what the frozen code
    does and the window stays eight characters wide.

    Args:
        value: The integer currently in the host variable.

    Returns:
        Exactly eight characters, before trimming.
    """
    begin = _EDIT_WINDOW_START - 1
    return _ws_mysql_edit(value)[begin:begin + _EDIT_WINDOW_LENGTH]


def _hv_numeric_text(value: int) -> str:
    """Render a numeric host variable as the bridge embeds it.

    The composition of the two rules above: edit into `WS-MYSQL-EDIT`, slice the
    fixed window, then `FUNCTION TRIM` the leading spaces off
    [common/analMT.cbl:L1000-L1004].

    Args:
        value: The integer currently in the host variable.

    Returns:
        The digit text the bridge places between its two quote characters.
    """
    return _function_trim(_ws_mysql_edit_window(value))



