def _unload_row(row: object, analysis: WsAnalysisRecord) -> None:
    """Move a fetched row into the host variables, then unload them.

    Reproduces the fetch pair the bridge performs at
    [common/analMT.cbl:L534-L542] and [common/analMT.cbl:L631-L639]::

        CALL "MySQL_fetch_record" USING WS-MYSQL-RESULT
                 HV-PA-CODE
                 HV-PA-GL
                 HV-PA-DESC
                 HV-PA-PRINT

    The foreign call writes the four host variables in the declared order and
    the caller then performs `bb100-UnloadHVs`. Here `dal/cursor_state.py`
    delivers the row as a mapping keyed by column name, so the four host
    variables are loaded from it by name in the same order and the unload
    follows - one hop of indirection fewer, the same two stages, the same
    receiving-field semantics.

    Args:
        row: The row `dal/cursor_state.py` fetched, a mapping of column name to
            value. Anything falsy is treated as no row and leaves the record
            untouched, matching a fetch that delivered nothing.
        analysis: The caller's record, written in place.
    """
    if not isinstance(row, Mapping):
        return
    td = _BRIDGE_WS.td
    td.hv_pa_code = _move_alphanumeric(
        _row_text(row, "PA-CODE"), _HV_PA_CODE_WIDTH
    )
    td.hv_pa_gl = abs(_row_int(row, "PA-GL")) % _HV_PA_GL_MODULUS
    td.hv_pa_desc = _move_alphanumeric(
        _row_text(row, "PA-DESC"), _HV_PA_DESC_WIDTH
    )
    td.hv_pa_print = _move_alphanumeric(
        _row_text(row, "PA-PRINT"), _HV_PA_PRINT_WIDTH
    )
    bb100_unload_hvs(td, analysis)


def _row_text(row: Mapping[str, object], column_name: str) -> str:
    """Read one character column out of a fetched row.

    Args:
        row: The fetched row.
        column_name: The column wanted.

    Returns:
        The value as text. A missing column yields spaces rather than raising,
        because the frozen host variables are initialised before the fetch and
        an unwritten one holds spaces - and because every column of this table
        is `NOT NULL` [mysql/ACASDB.sql:L32-L35], so a null cannot arrive from a
        conforming database.
    """
    value = row.get(column_name)
    if value is None:
        return ""
    if isinstance(value, bytes):
        # `char` columns arrive as text under the pinned converter; a driver
        # that hands back bytes is decoded rather than repr-ed into the record.
        return value.decode("utf-8", "replace")
    return str(value)


def _row_int(row: Mapping[str, object], column_name: str) -> int:
    """Read the one numeric column out of a fetched row.

    `PA-GL` is `mediumint(6) unsigned NOT NULL` [mysql/ACASDB.sql:L33], so the
    pinned converter of `dal/connection.py` delivers it as an `int`. Text is
    accepted as well, because the bridge WRITES this column as a quoted string
    literal (anomaly N-numeric-quoted) and a database that echoes it back as
    text must still land in an integer field.

    Args:
        row: The fetched row.
        column_name: The column wanted.

    Returns:
        The value as an integer; zero when absent, matching the initialised host
        variable.
    """
    value = row.get(column_name)
    if value is None:
        return 0
    if isinstance(value, int):
        return int(value)
    if isinstance(value, bytes):
        value = value.decode("utf-8", "replace")
    text = _function_trim(str(value))
    if not text:
        return 0
    negative = text.startswith("-")
    digits = "".join(character for character in text if character.isdigit())
    if not digits:
        return 0
    magnitude = int(digits)
    return -magnitude if negative else magnitude



# =============================================================================
#  STATEMENT ASSEMBLY  -  the three statements this module owns
# =============================================================================
#
# `dal/cursor_state.py` owns the positioning statements - the sequential-read
# SELECT, the indexed SELECT and the START SELECT - because it owns the ISAM
# emulation those statements exist to serve: the key of reference, the relation
# mapping, the stored-result snapshot and the FS-Reply protocol. Agent Action
# Plan 0.1.1 is explicit that indexed-file semantics must be "emulated, not
# approximated ... not merely issue equivalent SQL", so re-deriving those
# statements here would be a second implementation of one emulation.
#
# What remains is the three data-modifying statements the bridge assembles in
# its own sections, and they are assembled here: `bb200-Insert`
# [common/analMT.cbl:L974-L1031], `bb300-Update` [common/analMT.cbl:L1036-L1097]
# and the inline DELETE of `ba080-Process-Delete` [common/analMT.cbl:L828-L834].
#
# TWO REPRESENTATION-ONLY OMISSIONS, RECORDED AS OMISSIONS (rule R-5). Every
# frozen statement ends with `X"00"`, the NUL the C interface needs to find the
# end of a COBOL fixed-length field, and all but the DELETE also append `";"`.
# Neither reaches the database as an effect: the NUL is a transport artefact and
# the semicolon is a statement terminator the driver supplies itself. Both are
# dropped, matching the choice `dal/cursor_state.py` made for the statements it
# owns, and the DELETE's missing semicolon is recorded as anomaly
# N-delete-nosemi rather than reproduced as a difference nothing can observe.

#: The comma-and-space separator between assignments
#: [common/analMT.cbl:L995-L996, :L1007-L1008, :L1016-L1017].
_ASSIGNMENT_SEPARATOR: Final[str] = ", "

#: The placeholder every value travels as. The frozen bridge embeds each value
#: as a quoted literal; `execute_statement` binds instead, which is the same
#: value with the quoting done by the driver rather than by string assembly.
_PLACEHOLDER: Final[str] = "%s"


def _quoted_table() -> str:
    """The table name, backtick-quoted.

    Reproduces the literal the bridge writes into every statement -
    `` '`ANALYSIS-REC`' `` [common/analMT.cbl:L491, :L611, :L734, :L830, :L985,
    :L1047]. The bridge hard-codes the backticks because the name contains a
    hyphen and is a syntax error without them; here the quoting goes through
    `quote_identifier` so the rule is applied rather than restated.

    Returns:
        The quoted table name.
    """
    return quote_identifier(TABLE)


def _assignment_list() -> str:
    """`` `PA-CODE`=%s, `PA-GL`=%s, `PA-DESC`=%s, `PA-PRINT`=%s ``.

    Built from :data:`COLUMNS`, so the order is the column ordinal order of
    [mysql/ACASDB.sql:L31] - which is the order the frozen bridge writes its
    four assignments in, and the order `bb000-HV-Load` moves its four fields in.
    Deriving it rather than writing it out is what makes the text byte-identical
    across processes, as rule R-6 requires.

    ALL FOUR COLUMNS ARE ALWAYS NAMED. Every column of this table is `NOT NULL`
    [mysql/ACASDB.sql:L32-L35], and the frozen bridge initialises the whole
    host-variable group before loading it [common/analMT.cbl:L942], so an unset
    field arrives as a space or a zero. Agent Action Plan 0.6.2 states the
    consequence: "the Python layer must default rather than omit". Nothing here
    ever omits a column and nothing ever binds a database null.

    Returns:
        The assignment list, in column-ordinal order.
    """
    return _ASSIGNMENT_SEPARATOR.join(
        f"{column.quoted}={_PLACEHOLDER}" for column in COLUMNS
    )


def _key_predicate() -> str:
    """`` `PA-CODE`=%s `` - the single-key predicate the bridge assembles.

    Reproduces the STRING at [common/analMT.cbl:L808-L816] (delete) and
    [common/analMT.cbl:L866-L874] (rewrite), which are character for character
    the same::

        string   "`"                   delimited by size
                 KeyName (KOR-x1)      delimited by space
                 "`"                   delimited by size
                 '="'                  delimited by size
                 Analysis-Rec (K:L)       delimited by size
                 '"'                   delimited by size

    `KeyName (KOR-x1)` is the thirty-character key-table entry taken
    `delimited by space`, so it contributes `PA-CODE` and not its padding; the
    key value is taken `delimited by size`, so it contributes all three
    characters INCLUDING any trailing space. That asymmetry is preserved by
    :func:`_key_value_for_predicate`.

    ONE PREDICATE, ONE KEY, NEVER COMPOUND. The bridge's own comment
    [common/analMT.cbl:L243-L245] explains why, and it is the clearest statement
    of the rule anywhere in the checkout::

        *> The START condition cannot be compounded, and it must use a
        *> Key of Reference within the record. (These are COBOL rules...)
        *> The interface defines which key and the relation condition.

    Returns:
        The predicate, with the value as a placeholder.
    """
    return f"{quote_identifier(KEY_OF_REFERENCE.column_name)}={_PLACEHOLDER}"


def _key_value_for_predicate(analysis: WsAnalysisRecord) -> str:
    """`Analysis-Rec (K:L)` - the key as the predicate takes it, UNTRIMMED.

    The reference modification the bridge applies after loading `K` and `L` from
    the key table [common/analMT.cbl:L802-L804, :L859-L861]: offset 1, length 3.
    It is taken `delimited by size`, so a key of two significant characters
    contributes `"AB "` and not `"AB"`.

    *** ANOMALY N-where-trim - REPRODUCED, NOT FIXED (rule R-4) ***

    THIS IS THE OPPOSITE OF WHAT THE SET LIST DOES, and the asymmetry is in the
    frozen source rather than introduced here: the assignments trim TRAILING
    only [common/analMT.cbl:L991, :L1012, :L1021], the predicate does not trim at
    all [common/analMT.cbl:L812], and the UPDATE then trims the assembled
    predicate on BOTH sides [common/analMT.cbl:L1090]. Three trimming rules for
    one three-character key. On a `char(3)` column under a PAD SPACE collation
    the two compare equal, so the difference is invisible in the result and
    visible in `WS-Log-Where` - which is exactly why it is reproduced rather
    than smoothed over.

    Args:
        analysis: The record whose key is wanted.

    Returns:
        Exactly `KOR-length` characters, starting at `KOR-offset`.
    """
    begin = _KOR_OFFSET - 1
    return _pa_code_text(analysis)[begin:begin + _KOR_LENGTH]


def _ws_where_with_pointer(predicate_text: str) -> str:
    """`WS-Where (1:J)` - the assembled predicate PLUS one trailing space.

    *** ANOMALY N-where-pointer - REPRODUCED, NOT FIXED (rule R-4) ***

    `J` is the STRING pointer [common/analMT.cbl:L258]. It is set to 1 before the
    STRING [common/analMT.cbl:L807] and the STRING leaves it addressing the
    position AFTER the last character written, so `WS-Where (1:J)` is one
    character longer than the text - and `ws-Where` is space-filled
    [common/analMT.cbl:L806], so that extra character is a space. Every use of
    the reference-modified form therefore carries it: the log field
    [common/analMT.cbl:L818] and, in the SELECT and DELETE statements, the
    statement text itself.

    `bb300-Update` is the one place the bridge compensates, wrapping the same
    expression in `FUNCTION TRIM` [common/analMT.cbl:L1090] - which is evidence
    the trailing space is an accident rather than an intention, and evidence
    that it is not to be repaired anywhere else.

    Args:
        predicate_text: The predicate as assembled.

    Returns:
        The predicate with the pointer's trailing space appended.
    """
    return predicate_text + " "


