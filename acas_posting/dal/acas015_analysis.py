@contextmanager
def _bridge_cursor(connection: object) -> Iterator[object]:
    """Yield a cursor for `dal/cursor_state.py` to execute its own statement on.

    The positioning verbs take a cursor and issue their statement themselves, so
    they cannot go through `execute_statement`, which owns one statement of its
    caller's. This is the narrowest possible bridge between the two: one cursor,
    closed on every path, no statement issued here and nothing fetched here.

    Args:
        connection: The connection `mysql_1000_open` returned.

    Yields:
        A DB-API cursor over that connection, or - when another bridge has closed
        the one process handle, anomaly A-8 - the stand-in that reports the
        driver's failure from ``execute``. The frozen bridge reports a dead
        session from its ``call "MySQL_query"``
        [copybooks/mysql-procedures.cpy:L165-L166], having no acquisition step of
        its own, so the failure must reach the statement rather than raise here.
    """
    cursor = acquire_cursor(connection)  # type: ignore[arg-type]
    try:
        yield cursor
    finally:
        try:
            cursor.close()
        except Exception as error:  # pragma: no cover - driver-specific
            # A cursor that will not close is not a condition the frozen source
            # has an error path for, and raising from a `finally` would replace
            # the caller's own status with a misleading exception. Recorded and
            # dropped, exactly as `connection.py` does for the same case.
            _LOG.debug(
                "%s: closing the positioning cursor reported %s",
                HANDLER,
                sanitise_for_log(str(error)),
            )


def _affected_rows(cursor: object) -> int:
    """`call "MySQL_affected_rows" using WS-Mysql-Count-Rows`.

    The count `Mysql-1210-Command` collects after every command
    [copybooks/mysql-procedures.cpy:L178] and the value the three
    data-modifying paragraphs then test - `not = 1`
    [common/analMT.cbl:L781, :L836, :L882].

    MySQL reports rows CHANGED rather than rows matched, so an UPDATE that
    assigns a row its existing values reports zero. That is not corrected here:
    it is what the frozen bridge sees, and `ba090-Process-Rewrite`'s behaviour on
    a zero count - leaving the caller's status untouched - is anomaly
    N-stale-status, reproduced at its own site.

    `File-Access`'s own `WS-Count-Rows` [copybooks/wsfnctn.cob:L55] is NOT
    written, because this bridge never writes it; that field's comment records it
    as "used in Delete-All in valueMT", a verb this handler does not publish.

    Args:
        cursor: The cursor the statement was executed on.

    Returns:
        The affected-row count, or zero when the driver does not report one.
    """
    reported = getattr(cursor, "rowcount", None)
    if not isinstance(reported, int) or reported < 0:
        return 0
    return reported



