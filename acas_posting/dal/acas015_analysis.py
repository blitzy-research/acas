def _initialize_analysis_rec(analysis: WsAnalysisRecord) -> None:
    """`initialize Analysis-Rec` - spaces to the alphanumerics, zero to the number.

    *** ANOMALY N-initialize - RECORDED, AND BOTH FORMS REPRODUCED (rule R-4) ***

    One bridge, two initialisation semantics. [common/analMT.cbl:L561] writes
    `initialize Analysis-Rec with filler` inside the read-next error arm, while
    [common/analMT.cbl:L963] writes plain `initialize Analysis-Rec` at the head
    of the unload. `WITH FILLER` extends the initialisation to FILLER items,
    which is a real difference in `glbatchMT`, `slpostingMT`, `salesMT` and
    `valueMT` - and is NOT one here, because neither
    `01 WS-Analysis-Record` [copybooks/wsanal.cob:L9-L17] nor the bridge's own
    inline `01 Analysis-Rec` [common/analMT.cbl:L315-L319] declares a single
    `filler`. So the two statements have identical effect on THIS record, and
    one helper serves both sites. That is a finding, not a shortcut: the
    divergence is recorded, and it is recorded as having no observable
    consequence for this table rather than being quietly harmonised.

    The three key sub-fields are initialised individually, because the copybook
    declares the key as a group of three one-character items
    [copybooks/wsanal.cob:L10-L14] and a group has no elementary store of its
    own.

    Args:
        analysis: The caller's `WS-Analysis-Record`, written in place - which is
            what the frozen statement does, the bridge's `Analysis-Rec` being a
            LINKAGE SECTION item [common/analMT.cbl:L289, :L315] and therefore
            the very storage the handler passed in.
    """
    analysis.ws_pa_code.pa_system = _move_alphanumeric(" ", 1)
    analysis.ws_pa_code.pa_group.pa_first = _move_alphanumeric(" ", 1)
    analysis.ws_pa_code.pa_group.pa_second = _move_alphanumeric(" ", 1)
    analysis.pa_gl = 0
    analysis.pa_desc = _move_alphanumeric(" ", _HV_PA_DESC_WIDTH)
    analysis.pa_print = _move_alphanumeric(" ", _HV_PA_PRINT_WIDTH)


def _pa_code_text(analysis: WsAnalysisRecord) -> str:
    """Join the copybook's three-level key group into the bridge's flat three bytes.

    *** ANOMALY N-flatkey - REPRODUCED, NOT FIXED (rule R-4) ***

    The copybook declares the key as a group of a group
    [copybooks/wsanal.cob:L10-L14]::

        03  WS-Pa-Code.
            05  Pa-System     pic x.
            05  Pa-Group.
                07  Pa-First  pic x.
                07  Pa-Second pic x.

    and the bridge re-declares the same three bytes as one flat item with the
    `WS-` prefix dropped [common/analMT.cbl:L315] - `03 Pa-Code pic xxx.` So
    `Pa-System`, `Pa-Group`, `Pa-First` and `Pa-Second` have NO host variable
    and NO column; all four survive only inside `PA-CODE`'s three characters,
    and `omitted_copybook_fields` records each as a deliberate omission per
    rule R-5. No column is invented for any of them, and the group is NOT
    restored on the way out.

    Args:
        analysis: The record whose key group is to be flattened.

    Returns:
        Exactly three characters, in declaration order.
    """
    joined = (
        _move_alphanumeric(analysis.ws_pa_code.pa_system, 1)
        + _move_alphanumeric(analysis.ws_pa_code.pa_group.pa_first, 1)
        + _move_alphanumeric(analysis.ws_pa_code.pa_group.pa_second, 1)
    )
    return _move_alphanumeric(joined, _HV_PA_CODE_WIDTH)


def bb000_hv_load(analysis: WsAnalysisRecord, td: TdAnalysisRec) -> None:
    """`bb000-HV-Load Section` [common/analMT.cbl:L934-L952].

    Loads the host variables from the record the caller passed, which is the
    direction every non-fetch action needs. The frozen section, verbatim::

        L942       initialize TD-ANALYSIS-REC.
        L943       move     PA-CODE            to HV-Pa-CODE
        L944       move     PA-GL              to HV-PA-GL
        L945       move     PA-DESC            to HV-Pa-Desc
        L946       move     Pa-Print           to HV-Pa-Print.

    followed by the maintainer's own note on what the section is NOT for
    [common/analMT.cbl:L948-L949] - "Loading HVs implies a non-Fetch action. RGs
    are handled separately for all such actions so they must not be loaded
    here."

    THE LOAD ORDER IS THE COLUMN ORDER, AND THE KEY IS LOADED. Both are worth
    stating because neither is universal across the bridge set: `nominalMT` and
    `glpostingMT` move their fields in an order that does not follow their
    tables, and `glpostingMT` never loads its key at all. Here the four moves
    run `PA-CODE`, `PA-GL`, `PA-DESC`, `PA-PRINT`, which is exactly the ordinal
    order of [mysql/ACASDB.sql:L31] and exactly the order `bind_parameters`
    returns.

    *** ANOMALY N-hvcase - RECORDED, NOT NORMALISED (rule R-4) ***

    The casing is chaotic in both directions and in both operands. The
    receiving names read `HV-Pa-CODE`, `HV-PA-GL`, `HV-Pa-Desc`, `HV-Pa-Print`
    against declarations that are uniformly upper case
    [common/analMT.cbl:L283-L286], and the sending names mix `PA-CODE` with
    `Pa-Print`. `valueMT` has the same disease in lower case. COBOL is
    case-insensitive so nothing breaks, and nothing here is tidied: the Python
    attribute names follow the DECLARATIONS, and the divergence is recorded
    where it belongs, in the anomaly log.

    Only the final move of the block carries a terminating period - the
    `nominalMT` and `valueMT` style, unlike `slpostingMT` where every move has
    one. It has no effect on behaviour and is recorded for completeness.

    Args:
        analysis: The caller's `WS-Analysis-Record`, read only.
        td: The host-variable group, written in place.
    """
    # [common/analMT.cbl:L942] - plain `initialize`, and FIRST, which is what
    # makes the NOT NULL invariant hold: every column is supplied on every
    # statement and nothing is ever bound as a database null.
    initialised = TdAnalysisRec.initialize()
    td.hv_pa_code = initialised.hv_pa_code
    td.hv_pa_gl = initialised.hv_pa_gl
    td.hv_pa_desc = initialised.hv_pa_desc
    td.hv_pa_print = initialised.hv_pa_print

    # [common/analMT.cbl:L943] - the flattened key (anomaly N-flatkey).
    td.hv_pa_code = _pa_code_text(analysis)
    # [common/analMT.cbl:L944] - `PA-GL pic 9(6)` widening into
    # `HV-PA-GL pic 9(08) COMP`. The dictionary records the drift for this field
    # as "copybook has 6 digits, bridge host variable has 8"; the widening
    # cannot lose a digit, so this store is exact for every value the sending
    # field can hold. The truncation and the sign drop are written out anyway,
    # because the receiving field is eight digits and unsigned and a store into
    # it has those semantics whatever the sender happens to be.
    td.hv_pa_gl = abs(int(analysis.pa_gl)) % _HV_PA_GL_MODULUS
    # [common/analMT.cbl:L945]
    td.hv_pa_desc = _move_alphanumeric(analysis.pa_desc, _HV_PA_DESC_WIDTH)
    # [common/analMT.cbl:L946]
    td.hv_pa_print = _move_alphanumeric(analysis.pa_print, _HV_PA_PRINT_WIDTH)


