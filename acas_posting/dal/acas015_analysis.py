class CommandResult(NamedTuple):
    """What `PERFORM MYSQL-1210-COMMAND THRU MYSQL-1219-EXIT` leaves behind.

    The frozen paragraph [copybooks/mysql-procedures.cpy:L164-L181] issues the
    statement, routes a non-zero return code through `Mysql-1100-Db-Error`, and
    then collects `MySQL_affected_rows` into `WS-Mysql-Count-Rows`. Both results
    are carried, because the three data-modifying paragraphs test the count AND
    then re-read the diagnostics.

    Attributes:
        count: `WS-Mysql-Count-Rows` after the command - rows CHANGED, which is
            what MySQL reports and what `not = 1` is tested against.
        error: The `DbErrorStatus` `Mysql-1100-Db-Error` produced, or `None` when
            the statement succeeded. Carried so a caller can apply its own
            `WE-Error` override, which is what the delete and rewrite paragraphs
            do [common/analMT.cbl:L845, :L891].
    """

    count: int
    error: object | None


def _driver_errno(error: BaseException) -> str:
    """`call "MySQL_errno" using WS-MYSQL-Error-Number`.

    The driver exposes the same number the C function returned. It is read
    without importing the driver, so this module keeps a single dependency on
    `dal/connection.py` for everything driver-shaped.

    Args:
        error: The exception the statement raised.

    Returns:
        The error number as text, five characters or fewer. When the driver
        reports none, a value that does NOT begin with a zero digit is returned -
        every frozen test is `WS-MYSQL-Error-Number (1:1) not = "0"`
        [common/analMT.cbl:L785, :L840, :L886], so a failure whose number began
        with zero would be read as a success and its diagnostics discarded.
    """
    reported = getattr(error, "errno", None)
    if reported is None:
        return "99999"
    text = _function_trim(str(reported))
    if not text or text.startswith("0"):
        return "99999"
    return text


def _driver_sqlstate(error: BaseException) -> str:
    """`call "MySQL_sqlstate" using WS-MYSQL-SQLstate`.

    Args:
        error: The exception the statement raised.

    Returns:
        The SQLSTATE as text, or spaces when the driver reports none - which is
        what the uninitialised `WS-Mysql-SqlState` holds
        [copybooks/mysql-variables.cpy:L85].
    """
    reported = getattr(error, "sqlstate", None)
    if reported is None:
        return " " * _WS_MYSQL_SQLSTATE_WIDTH
    return str(reported)


def _driver_message(error: BaseException) -> str:
    """`call "MySQL_error" using WS-MYSQL-Error-Message`.

    Args:
        error: The exception the statement raised.

    Returns:
        The driver's message text. It crosses the 160-character intermediate in
        :func:`_apply_db_error`, so no caller sees more than that (anomaly
        N-msg160).
    """
    reported = getattr(error, "msg", None)
    if reported:
        return str(reported)
    return str(error)


def _issue_command(
    file_access: FileAccess, statement: str, parameters: tuple[str, ...]
) -> CommandResult:
    """`PERFORM MYSQL-1210-COMMAND THRU MYSQL-1219-EXIT`.

    Reproduces [copybooks/mysql-procedures.cpy:L164-L181]: one `MySQL_query`,
    the error ladder on a non-zero return code, then the affected-row count. The
    commented-out lock-retry block at [copybooks/mysql-procedures.cpy:L167-L175]
    is dead in the frozen source and nothing is retried here either; `status.py`
    records that ladder as its own anomaly.

    NOTHING RAISES. [common/analMT.cbl:L660] states the contract - "Any errors
    leave it to caller to recover from" - and the C interface it describes turns
    every failure into a return code, never into an unwind. So the statement is
    guarded broadly and any failure becomes a status pair, exactly as the frozen
    program's caller expects to receive one.

    `Mysql-1100-Db-Error`'s own INSERT special case
    [copybooks/mysql-procedures.cpy:L100-L104] - which yields `FS-Reply` 22 and
    leaves `WE-Error` alone when the command text starts with `INSERT` - is
    applied by `dal/status.py`, so the statement text is passed to it verbatim.

    Args:
        file_access: The caller's `File-Access`; the diagnostic fields and the
            status pair are written when the statement fails.
        statement: The statement to issue, identifiers already quoted.
        parameters: The values to bind, in the statement's own order.

    Returns:
        The count and, on failure, the classified error.
    """
    connection = _connection_or_none()
    try:
        with execute_statement(connection, statement, parameters) as cursor:
            return CommandResult(_affected_rows(cursor), None)
    except Exception as error:  # noqa: BLE001 - the frozen contract never raises
        status = mysql_1100_db_error(
            errno=_driver_errno(error),
            message=_driver_message(error),
            sql_state=_driver_sqlstate(error),
            command=statement,
            we_error=int(file_access.we_error),
        )
        _apply_db_error(file_access.logging_data, status)
        _set_status(file_access, int(status.fs_reply), int(status.we_error))
        return CommandResult(0, status)


