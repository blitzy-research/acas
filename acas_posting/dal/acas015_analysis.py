def _unload_row(row: object, analysis: WsAnalysisRecord) -> None:
    """Move a fetched row into the host variables, then unload them.

    The foreign call writes the four host variables in the declared order and the caller
    then performs `bb100-UnloadHVs`.

    Args:
        row: The row `dal/cursor_state.py` fetched, a mapping of column name to value.
        analysis: The caller's record, written in place.
    """
    if not isinstance(row, Mapping):
        return
    td = _BRIDGE_WS.td
    td.hv_pa_code = _move_alphanumeric(
        _row_text(row, "PA-CODE"), _HV_PA_CODE_WIDTH
    )
    td.hv_pa_gl = abs(_row_int(row, "PA-GL")) % _HV_PA_GL_MODULUS
