def _columns_from_dictionary() -> tuple[AnalysisColumn, ...]:
    """Read the four columns out of the generated data dictionary.

    Nothing here reads a picture clause, a host-variable declaration or a column type
    out of the frozen source by eye.

    Returns:
        The four columns in column-ordinal order.

    Raises:
        LookupError: The dictionary does not describe this table with four columns each
            carrying an ordinal.
    """
    entries = loader.entries_for_table(TABLE)
    columns: list[AnalysisColumn] = []
    for entry in entries:
        column = entry.column
        if column is None or column.ordinal is None:
            raise LookupError(
                f"the generated data dictionary describes {entry.key} without "
                f"a column ordinal, so the column order of {TABLE} "
                f"[mysql/ACASDB.sql:L31] cannot be reproduced; regenerate "
                f"data_dictionary/acas_posting_dictionary.json"
            )
        copybook = entry.copybook
        host_variable = entry.bridge_host_variable
        drift = loader.drift_for(entry.key)
        columns.append(
            AnalysisColumn(
                ordinal=int(column.ordinal),
                column_name=column.name,
                quoted=quote_identifier(column.name),
                entry_key=entry.key,
                citation=loader.cite(entry.key),
                copybook_field="" if copybook is None else copybook.name,
                host_variable="" if host_variable is None else host_variable.name,
                host_variable_digits=(
                    None if host_variable is None else host_variable.digits
                ),
                host_variable_length=(
                    None if host_variable is None else host_variable.character_length
                ),
                python_storage=str(entry.cobol_python_storage),
                is_primary_key=bool(column.is_primary_key),
                drift_details=tuple(drift.details),
            )
        )
    columns.sort(key=lambda column: column.ordinal)
    if len(columns) != 4:
        raise LookupError(
            f"{TABLE} [mysql/ACASDB.sql:L31] declares four columns and the "
            f"bridge declares four host variables [common/analMT.cbl:"
            f"L283-L286], but the generated dictionary yielded "
            f"{len(columns)}; regenerate "
            f"data_dictionary/acas_posting_dictionary.json"
        )
    return tuple(columns)


