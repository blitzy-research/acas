def _ws_pic_9_4(value: int) -> str:
    """Render a `pic 9(4)` DISPLAY item as the four characters it holds.

    `A` and `B` are declared `77 ... pic 9(4) value zero`
    [common/acas015.cbl:L251-L252], and a `pic 9(4)` in a STRING statement
    `delimited by size` contributes all four of its bytes - zero-filled on the
    left, no sign and no decimal point.

    Args:
        value: The integer the field holds.

    Returns:
        Exactly four digit characters. A value too large for the field is
        truncated on the LEFT, which is what a MOVE into `pic 9(4)` does.
    """
    return f"{abs(int(value)) % 10000:04d}"


